"""Clean the hidden properties of an Office file we generate (File > Info in Word).

The libraries that build our files sign them: python-docx writes author "python-docx" and the
comment "generated by python-docx", python-pptx and openpyxl leave their own names. A proposal
must carry nothing but the company's name, so every file we make passes through here.
"""
from __future__ import annotations

import io
import re
import zipfile
from xml.sax.saxutils import escape

_CORE = "docProps/core.xml"
_SET = ("dc:creator", "cp:lastModifiedBy")             # who made it: the company
_CLEAR = ("dc:description", "cp:keywords", "dc:subject")  # tool notes: nothing


def _put(xml: str, tag: str, value: str) -> str:
    value = escape(value)
    full = re.compile(rf"<{tag}(\s[^>]*)?>.*?</{tag}>", re.S)
    empty = re.compile(rf"<{tag}(\s[^>]*)?/>")
    if full.search(xml):
        return full.sub(lambda m: f"<{tag}{m.group(1) or ''}>{value}</{tag}>", xml)
    if empty.search(xml):
        return empty.sub(lambda m: f"<{tag}{m.group(1) or ''}>{value}</{tag}>", xml)
    if value:  # absent: add it, so a viewer shows the company rather than nothing
        return xml.replace("</cp:coreProperties>", f"<{tag}>{value}</{tag}></cp:coreProperties>")
    return xml


def clean(content: bytes, author: str = "") -> bytes:
    """The same file with the tool's name replaced by `author` and its notes removed. Anything
    that isn't an Office file comes back untouched."""
    try:
        src = zipfile.ZipFile(io.BytesIO(content))
        if _CORE not in src.namelist():
            return content
    except zipfile.BadZipFile:
        return content
    xml = src.read(_CORE).decode("utf-8")
    for tag in _SET:
        xml = _put(xml, tag, author)
    for tag in _CLEAR:
        xml = _put(xml, tag, "")
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as dst:
        for info in src.infolist():
            data = xml.encode("utf-8") if info.filename == _CORE else src.read(info.filename)
            dst.writestr(info, data)
    return out.getvalue()
